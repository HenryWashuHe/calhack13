// Generate TypeScript types from the Rust-exported JSON Schemas in /schemas.
// Run after `cargo run -p genesis-server -- export-schemas`.
import { compile } from "json-schema-to-typescript";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, "../../../schemas");
const out = join(here, "../src/lib/contracts.ts");
const files = readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort();

const seen = new Set();
let body = "";
for (const file of files) {
  const schema = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
  const name = file.replace(".schema.json", "");
  const ts = await compile(schema, name, {
    bannerComment: "",
    additionalProperties: false,
    format: true,
  });
  // Drop declarations already emitted by an earlier schema (shared definitions).
  const chunks = ts.split(/\n(?=export )/);
  for (const chunk of chunks) {
    const m = chunk.match(/^export (?:type|interface) (\w+)/);
    if (m) {
      if (seen.has(m[1])) continue;
      seen.add(m[1]);
    }
    body += chunk.trimEnd() + "\n\n";
  }
}
const banner = `/* eslint-disable */\n// GENERATED by scripts/gen-types.mjs from /schemas (Rust is the source of truth).\n// Do not edit by hand.\n\n`;
writeFileSync(out, banner + body.trimEnd() + "\n");
console.log(`wrote ${out} (${seen.size} types from ${files.length} schemas)`);
