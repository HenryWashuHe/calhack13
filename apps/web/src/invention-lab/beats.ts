// Eric's Claude: which records exist for each beat of the proposed A → B → A
// sequence (docs/INVENTION_LAB_DEMO.md, docs/invention-lab/ui.md#beat-checklist).
// This reports presence of records only. It never marks a G0–G4 gate complete
// and never infers improvement; the operator names which org is A and which is B.

import { adoptionLabel, executionLabel, revisionLabel, verdictText } from "./claims";
import type { Lineage } from "./lineage";

export interface Fact {
  text: string;
  recorded: boolean;
}
export interface Beat {
  title: string;
  facts: Fact[];
}

export const BEATS_LIMIT =
  "Presence of records only. Gate completion (G0–G4) is judged against docs/ONGOING_GOAL.md, not by this view.";

function runsText(l: Lineage, org: string, methods: Set<string>): Fact {
  const runs = l.executions.filter((e) => e.receipt.org_id === org && methods.has(e.method));
  if (runs.length === 0) return { text: `${org} runs: none recorded`, recorded: false };
  const outcomes = runs.map((r) => `${executionLabel(r.receipt.outcome).text} (${r.evaluations.length} evaluation${r.evaluations.length === 1 ? "" : "s"})`);
  return { text: `${org} runs: ${outcomes.join("; ")}`, recorded: true };
}

/** Trials in which `org` ran one of `methods` as the candidate. A trial
 * verdict is scoring evidence, not an adoption decision. */
export function trialsOf(l: Lineage, org: string, methods: Set<string>) {
  return l.trials.filter((t) =>
    t.executions.some(
      (e) =>
        e.receipt.org_id === org &&
        methods.has(e.method) &&
        (e.receipt.purpose.kind === "comparison" || (e.receipt.purpose.kind === "acceptance" && e.receipt.purpose.role === "candidate")),
    ),
  );
}
function trialsText(l: Lineage, org: string, methods: Set<string>, what: string): Fact {
  const found = trialsOf(l, org, methods);
  if (found.length === 0) return { text: `${org} trials of ${what}: none recorded`, recorded: false };
  const list = found.map((t) => `${t.plan.ref.id}: ${verdictText(t.verdict)}`).join("; ");
  return { text: `${org} trials of ${what}: ${list} (trial verdicts, not adoption decisions)`, recorded: true };
}

export function beats(l: Lineage, a: string, b: string): Beat[] {
  const generatedBy = (org: string) =>
    new Set(l.edges.flatMap((e) => (e.kind === "generated" && e.org_id === org ? [e.to] : [])));
  const aMethods = generatedBy(a);
  const revisions = l.edges.flatMap((e) => (e.kind === "revised_from" && e.org_id === b && aMethods.has(e.from) ? [e] : []));
  const bRevisions = new Set(revisions.map((r) => r.to));
  const decisions = (org: string, methods: Set<string>) =>
    l.edges.flatMap((e) => (e.kind === "adoption" && e.org_id === org && methods.has(e.to) ? [e] : []));

  const aAttempts = l.attempts.filter((x) => x.status.org_id === a);
  const aPackages = aAttempts.filter((x) => x.status.package).length;
  const bDecisions = decisions(b, aMethods);
  const aDecisions = decisions(a, bRevisions);
  const decisionText = (ds: typeof bDecisions) =>
    ds.map((d) => (d.kind === "adoption" ? adoptionLabel(d.outcome.outcome).text + (d.pairing === "host" ? " (pairing supplied by host)" : "") : "")).join("; ");

  // Verdict kinds of A's trials of B's revisions, e.g. "2 rejected": evidence of
  // evaluation, not a decision, so the chain stays incomplete without one.
  const counts = new Map<string, number>();
  for (const t of trialsOf(l, a, bRevisions)) {
    const v = t.verdict?.verdict;
    const k = v === undefined ? "without a verdict" : ["accepted", "rejected", "insufficient"].includes(v) ? v : `unrecognized verdict ${v}`;
    counts.set(k, (counts.get(k) ?? 0) + 1);
  }
  const aTrialNote = [...counts].map(([k, n]) => `${n} ${k}`).join(", ");
  const chainMissing = [
    aPackages === 0 && `a method generated by ${a}`,
    revisions.length === 0 && `a revision by ${b}`,
    aDecisions.length === 0 &&
      `${a}'s decision on that revision` + (aTrialNote ? ` (${a}'s trials of it are recorded: ${aTrialNote})` : ""),
  ].filter((x): x is string => Boolean(x));

  return [
    {
      title: `${a} invents`,
      facts: [
        { text: `${a} generation attempts: ${aAttempts.length}, ${aPackages} with a package`, recorded: aAttempts.length > 0 },
        runsText(l, a, aMethods),
      ],
    },
    {
      title: `${b} inherits selectively`,
      facts: [
        bDecisions.length
          ? { text: `${b} decisions on ${a}'s methods: ${decisionText(bDecisions)}`, recorded: true }
          : { text: `${b} decisions on ${a}'s methods: none recorded`, recorded: false },
        runsText(l, b, aMethods),
        trialsText(l, b, aMethods, `${a}'s methods`),
      ],
    },
    {
      title: `${b} revises the method`,
      facts: [
        revisions.length
          ? { text: `${b} revisions of ${a}'s methods: ${revisions.map((r) => (r.kind === "revised_from" ? revisionLabel(r.source_changed).text : "")).join("; ")}`, recorded: true }
          : { text: `${b} revisions of ${a}'s methods: none recorded`, recorded: false },
        runsText(l, b, bRevisions),
        trialsText(l, b, bRevisions, "its revisions"),
      ],
    },
    {
      title: `${a} faces a fresh challenge`,
      facts: [
        aDecisions.length
          ? { text: `${a} decisions on ${b}'s revisions: ${decisionText(aDecisions)}`, recorded: true }
          : { text: `${a} decisions on ${b}'s revisions: none recorded`, recorded: false },
        runsText(l, a, bRevisions),
        trialsText(l, a, bRevisions, `${b}'s revisions`),
      ],
    },
    {
      title: "Network remembers",
      facts: [
        chainMissing.length === 0
          ? { text: `records exist for ${a} → ${b} revision → ${a} decision`, recorded: true }
          : { text: `chain incomplete; no record of ${chainMissing.join(", ")}`, recorded: false },
      ],
    },
  ];
}
