// Eric's Claude: the read-only lineage view (docs/invention-lab/ui.md#lineage-panel):
// beat checklist, exact method versions with their recorded origin, decisions
// and runs, reported problems, then every generation attempt. Not wired into
// the console.

import { AttemptLedger } from "./AttemptLedger";
import { Chip } from "./AttemptCard";
import { beats, BEATS_LIMIT } from "./beats";
import { adoptionLabel, evaluationLabel, executionLabel, purposeText, revisionLabel, TIER_TEXT } from "./claims";
import type { Lineage, MethodNode } from "./lineage";
import type { ExactRef } from "./records";

const short = (r: ExactRef) => `${r.id}@${r.version} ${r.sha256.slice(0, 12)}`;

function MethodCard({ node, lineage }: { node: MethodNode; lineage: Lineage }) {
  const byKey = new Map(lineage.nodes.map((n) => [n.key, n.ref]));
  const orgOf = new Map(lineage.attempts.map((a) => [a.status.operation_id, a.status.org_id]));
  const into = lineage.edges.filter((e) => e.to === node.key);
  const runs = lineage.executions.filter((e) => e.method === node.key);
  return (
    <article className="lab-method">
      <header>
        <code>{short(node.ref)}</code>
      </header>
      <ul>
        {into.length === 0 && <li>origin not recorded in the supplied files</li>}
        {into.map((e, i) =>
          e.kind === "generated" ? (
            <li key={i}>
              generated by {orgOf.get(e.operation_id)} in <code>{e.operation_id}</code>
            </li>
          ) : e.kind === "revised_from" ? (
            <li key={i}>
              revised by {e.org_id} from <code>{short(byKey.get(e.from)!)}</code> <Chip label={revisionLabel(e.source_changed)} />
            </li>
          ) : (
            <li key={i}>
              {e.org_id}: <Chip label={adoptionLabel(e.outcome.outcome)} />
              {e.outcome.installed?.verdict.verdict === "accepted" &&
                "candidate" in e.outcome.installed.verdict &&
                ` candidate ${e.outcome.installed.verdict.candidate}/${e.outcome.installed.verdict.of} vs control ${e.outcome.installed.verdict.control}/${e.outcome.installed.verdict.of}`}
              {e.outcome.reason && ` — ${e.outcome.reason}`}
              {e.pairing === "host" && " (pairing supplied by host)"}
            </li>
          ),
        )}
        {runs.map((r) => (
          <li key={`${r.receipt.org_id}/${r.receipt.run_id}/${r.receipt.attempt_id}`}>
            run by {r.receipt.org_id} <code>{r.receipt.run_id}</code>, {purposeText(r.receipt.purpose)}:{" "}
            <Chip label={executionLabel(r.receipt.outcome)} /> {TIER_TEXT.local_process}
            {r.evaluations.map((v) => (
              <span key={v.request_id}>
                {" "}
                · <Chip label={evaluationLabel(v.outcome)} />{" "}
                {v.metrics ? <code>{short(v.metrics)}</code> : v.reason}
                {" (matched by output and purpose)"}
              </span>
            ))}
          </li>
        ))}
      </ul>
    </article>
  );
}

export function LineagePanel({ lineage, orgA, orgB }: { lineage: Lineage; orgA?: string; orgB?: string }) {
  return (
    <section className="lab-lineage">
      {orgA && orgB ? (
        <section className="lab-beats">
          <h3>
            A → B → A records ({orgA} as A, {orgB} as B)
          </h3>
          <ol>
            {beats(lineage, orgA, orgB).map((beat) => (
              <li key={beat.title}>
                <strong>{beat.title}</strong>
                <ul>
                  {beat.facts.map((f) => (
                    <li key={f.text} data-recorded={f.recorded}>
                      {f.recorded ? "recorded: " : "no record: "}
                      {f.text}
                    </li>
                  ))}
                </ul>
              </li>
            ))}
          </ol>
          <p className="lab-limit">{BEATS_LIMIT}</p>
        </section>
      ) : (
        <p>Choose which organization is A and which is B to see the A → B → A checklist.</p>
      )}
      <h3>Method versions</h3>
      {lineage.nodes.length === 0 ? (
        <p>No exact method version is recorded in the supplied files.</p>
      ) : (
        lineage.nodes.map((n) => <MethodCard key={n.key} node={n} lineage={lineage} />)
      )}
      {lineage.problems.length > 0 && (
        <>
          <h3>Problems in the supplied records</h3>
          <ul>
            {lineage.problems.map((p) => (
              <li key={p}>{p}</li>
            ))}
          </ul>
        </>
      )}
      <AttemptLedger attempts={lineage.attempts} />
    </section>
  );
}
