// Eric's Claude: intake of the two committed live evidence folders, the
// A → B → A beat checklist and the lineage panel. The complete chain below is
// synthetic: no generated method has been executed, adopted or revised yet.
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { beats } from "./beats";
import { intake, orgsIn } from "./intake";
import { buildLineage, type LabRecords } from "./lineage";
import { LineagePanel } from "./LineagePanel";
import { decodeAdoptionOutcome, decodeGenerationStatus, decodeRevisionObservation, type ExactRef } from "./records";
import a1 from "../../../../docs/invention-lab/evidence/live-method-20261024/admission.json";
import s1 from "../../../../docs/invention-lab/evidence/live-method-20261024/final-status.json";
import g1 from "../../../../docs/invention-lab/evidence/live-method-20261024/generation.json";
import p1 from "../../../../docs/invention-lab/evidence/live-method-20261024/prepared-generation.json";
import r1 from "../../../../docs/invention-lab/evidence/live-method-20261024/roster.json";
import s2 from "../../../../docs/invention-lab/evidence/live-method-20261024-diagnostic/final-status.json";
import g2 from "../../../../docs/invention-lab/evidence/live-method-20261024-diagnostic/generation.json";
import p2 from "../../../../docs/invention-lab/evidence/live-method-20261024-diagnostic/prepared-generation.json";
import m2 from "../../../../docs/invention-lab/evidence/live-method-20261024-diagnostic/run-metadata.json";

const file = (name: string, v: unknown) => ({ name, text: JSON.stringify(v) });
const liveFiles = [
  file("1/prepared-generation.json", p1),
  file("1/final-status.json", s1),
  file("1/generation.json", g1),
  file("1/admission.json", a1),
  file("1/roster.json", r1),
  file("2/generation.json", g2),
  file("2/prepared-generation.json", p2),
  file("2/final-status.json", s2),
  file("2/run-metadata.json", m2),
  { name: "2/README.md", text: "# Second live method-generation attempt" },
];
const textOf = (html: string) => html.replace(/<[^>]+>/g, " ").replace(/&#x27;/g, "'").replace(/\s+/g, " ");

describe("intake of the two failed live attempts", () => {
  const ready = intake(liveFiles);

  it("uses each status with its same-phase checkpoint and lists every other file with a reason", async () => {
    const i = await ready;
    expect(i.used.map((n) => `${n.file}: ${n.note}`).sort()).toEqual([
      "1/final-status.json: generation status",
      "1/generation.json: generation checkpoint (outcome enum only)",
      "2/final-status.json: generation status",
      "2/generation.json: generation checkpoint (outcome enum only)",
    ]);
    expect(i.skipped.find((n) => n.file === "1/prepared-generation.json")!.note).toBe(
      "generation checkpoint in phase prepared; the status for live-a-method-20261024t152819z-2a3e0b5a is failed",
    );
    expect(i.skipped.find((n) => n.file === "2/README.md")!.note).toBe("not JSON");
    expect(i.skipped.find((n) => n.file === "1/roster.json")!.note).toBe("not a record type this view reads");
    expect(orgsIn(i)).toEqual(["org_example_a"]);
  });

  it("shows A's two failed attempts and no record for any later beat", async () => {
    const l = buildLineage((await ready).records);
    expect(l.problems).toEqual([]);
    const b = beats(l, "org_example_a", "org_example_b");
    expect(b[0]!.facts).toEqual([
      { text: "org_example_a generation attempts: 2, 0 with a package", recorded: true },
      { text: "org_example_a runs: none recorded", recorded: false },
    ]);
    expect(b.slice(1).flatMap((x) => x.facts).every((f) => !f.recorded)).toBe(true);
    expect(b[4]!.facts[0]!.text).toBe(
      "chain incomplete; no record of a method generated by org_example_a, a revision by org_example_b, org_example_a's decision on that revision",
    );
  });

  it("renders no method version, the checklist and the ledger", async () => {
    const text = textOf(renderToStaticMarkup(<LineagePanel lineage={buildLineage((await ready).records)} orgA="org_example_a" orgB="org_example_b" />));
    expect(text).toContain("No exact method version is recorded in the supplied files.");
    expect(text).toContain("no record: org_example_b revisions of org_example_a's methods: none recorded");
    expect(text).toContain("2 attempts · 2 generation failed · 0 packages");
    expect(text).toContain("Presence of records only.");
  });
});

describe("intake edge cases", () => {
  it("skips adoption outcomes that cannot name their receiver, and malformed records", async () => {
    const i = await intake([
      file("na.json", { outcome: "not_applicable", reason: "0/3" }),
      file("bad.json", { binding: {}, actual_method: {}, outputs: [], transcript: {} }),
      { name: "list.json", text: "[1]" },
    ]);
    expect(i.used).toEqual([]);
    expect(i.skipped.map((n) => n.note)).toEqual([
      'adoption outcome "not_applicable" does not name its receiver or method; needs host pairing',
      "malformed: execution.binding.org_id: expected string",
      "not a JSON object",
    ]);
  });
});

describe("a complete synthetic chain", () => {
  const ref = (id: string, c: string): ExactRef => ({ domain: "d", schema: "s", id, version: "1", sha256: c.repeat(64) });
  const v1 = ref("a-method", "a");
  const v2 = ref("b-method", "b");
  const status = (op: string, org: string, pkg: ExactRef) =>
    decodeGenerationStatus({ ...structuredClone(s2), operation_id: op, org_id: org, phase: "generated", package: pkg, diagnostic: null, transport: "loopback_fixture" });
  const records: LabRecords = {
    generations: [{ status: status("op-a", "org_a", v1) }, { status: status("op-b", "org_b", v2) }],
    revisions: [decodeRevisionObservation({ schema: "genesis-method-revision-observation/1", parent: v1, child: v2, org_id: "org_b", operation_id: "op-b", transport: "loopback_fixture", source_changed: true })],
    adoptions: [
      { receiver_org: "org_b", offer: v1, outcome: decodeAdoptionOutcome({ outcome: "adopted", installation: { org_id: "org_b", method: v1, verdict: { verdict: "accepted", candidate: 2, control: 1, of: 3 } } }) },
      { receiver_org: "org_a", offer: v2, outcome: decodeAdoptionOutcome({ outcome: "not_applicable", reason: "1/3 vs 2/3" }) },
    ],
  };

  it("marks each beat's decision facts recorded and the chain present, without any improvement wording", () => {
    const l = buildLineage(records);
    expect(l.problems).toEqual([]);
    const b = beats(l, "org_a", "org_b");
    expect(b.map((x) => x.facts[0]!.recorded)).toEqual([true, true, true, true, true]);
    expect(b[2]!.facts[0]!.text).toBe("org_b revisions of org_a's methods: source changed (bytes)");
    expect(b[3]!.facts[0]!.text).toBe("org_a decisions on org_b's revisions: not applicable here (pairing supplied by host)");
    expect(b[4]!.facts[0]!.text).toBe("records exist for org_a → org_b revision → org_a decision");
    const text = textOf(renderToStaticMarkup(<LineagePanel lineage={l} orgA="org_a" orgB="org_b" />));
    expect(text).toContain("candidate 2/3 vs control 1/3");
    expect(text).toContain("revised by org_b from");
    // Checklist and method sections only; attempt cards quote denials such as "not ... improvement".
    expect(text.split("Generation attempts")[0]).not.toMatch(/improv|better/i);
  });

  it("does not credit B's revision of a method A never generated", () => {
    const l = buildLineage({ ...records, generations: [records.generations[1]!] });
    expect(beats(l, "org_a", "org_b")[2]!.facts[0]!.recorded).toBe(false);
  });
});
